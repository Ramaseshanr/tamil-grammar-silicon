#!/usr/bin/env python3
"""
Generate the Tamil noun datapath's HDL sources and its oracle vectors.

The hardware must not drift from the Python. So the decision logic is not hand-written:
this emits it from the same fitted artefact `tools/derive_nouns.py` loads
(`data/derived/noun_rules_paired.json`), and emits the test vectors from
`derive_nouns.classify()` itself. If the rules are refitted, regenerate and the testbench
either still passes or tells you exactly which stem broke.

Same discipline as `SanskritOS/hardware/rtl/anvaya_verify.sv`, which records that it is a
transcription of a Rust engine and that the engine is the authority.

  python3 tools/gen_hdl.py

  hdl/src/classify_gen.rs        impl Logic for TamilNounClass  (RustHDL, #[hdl_gen])
  hdl/gen/tamil_classes.vh       class-code legend for the testbench
  hdl/vectors/class_vectors.txt  one line per real stem, from the Python oracle
"""
import os, sys, json, pathlib, collections
ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))

# The HDL is generated from the PAIRED rules -- 49 contexts, 99.89% of stems classified.
# derive_nouns defaults to the unpaired 40-context set, which classifies only 69.94%, so
# importing it without this would emit 13,087 vectors expecting "no class" against a
# classifier that has one. Forced here, and asserted below, rather than left to an
# environment variable somebody has to remember.
os.environ["TAMILOS_PAIRED"] = "1"
import tlp1 as T
import derive_nouns as D

RULES_PATH = ROOT / "data/derived/noun_rules_paired.json"
if D.RULES.resolve() != RULES_PATH.resolve():
    sys.exit(f"derive_nouns is using {D.RULES.name}, not {RULES_PATH.name}.\n"
             f"  The generator and the oracle must read the same classifier.")

HDL = ROOT / "hdl"
RULES = json.loads(RULES_PATH.read_text(encoding="utf-8"))
CM = RULES["classifier"]

U, TU_, RU_, N_, A_ = (T.encode(c)[0] for c in ("உ", "ட்", "ற்", "ன்", "அ"))

def class_codes():
    """Stable numbering. 0 is reserved for "context not in the fitted classifier"."""
    names = sorted(set(CM.values()))
    return {n: i + 1 for i, n in enumerate(names)}

CODE = class_codes()

# --------------------------------------------------------------- the decision, as Rust
def emit_rust():
    L = []
    a = L.append
    a("// GENERATED by tools/gen_hdl.py -- do not edit. Regenerate instead.")
    a("//")
    a("// A transcription of tools/derive_nouns.py::context() composed with the fitted")
    a("// `classifier` map. The Python is the authority; hdl/tb checks them against each")
    a("// other over every stem in the gold.")
    a("//")
    a("// #[hdl_gen] accepts neither casts nor named constants, so every TLP1 value appears")
    a("// as a bare literal. The comment on each line says which phoneme it is.")
    a("impl Logic for TamilNounClass {")
    a("    #[hdl_gen]")
    a("    fn update(&mut self) {")
    a("        self.cls.next = 0u64.into();")
    a("        self.ok.next = false;")
    a("")
    a("        // ---- branch 1: Naṉṉūl 181-182 kuṟṟiyalukaram, ṭu/ṟu-final and NOT doubled")
    a("        //      (a doubled ṭṭu/ṟṟu falls through to branch 3, which is why the fitted")
    a("        //       map has u/42/C but no u/42/V)")
    a(f"        if (self.len.val() > 2u64) & (self.p1.val() == {U:#04x}u64)")
    a(f"            & ((self.p2.val() == {TU_:#04x}u64) | (self.p2.val() == {RU_:#04x}u64))")
    a("            & !((self.len.val() >= 4u64) & (self.p3.val() == self.p2.val()))")
    a("        {")
    a("            self.ok.next = true;")
    a("            if (self.p3.val() & 0xc0u64) == 0x40u64 {          // is_mey(p3) -> clust")
    a(f"                self.cls.next = {CODE['NCLUST']}u64.into();")
    a("            } else if ((self.p3.val() & 0xc0u64) == 0x00u64)   // is_nedil(p3)")
    a("                & ((self.p3.val() & 0x08u64) == 0x08u64)")
    a("            {")
    a(f"                if self.p2.val() == {TU_:#04x}u64 {{")
    a(f"                    self.cls.next = {CODE['NDBLT']}u64.into();")
    a("                } else {")
    a(f"                    self.cls.next = {CODE['NDBLR']}u64.into();")
    a("                }")
    a("            } else if self.uyir.val() > 2u64 {                 // உயிர்த்தொடர்")
    a(f"                if self.p2.val() == {TU_:#04x}u64 {{")
    a(f"                    self.cls.next = {CODE['NDBLT']}u64.into();")
    a("                } else {")
    a(f"                    self.cls.next = {CODE['NDBLR']}u64.into();")
    a("                }")
    a("            } else {                                            // முற்றியலுகரம்")
    a(f"                self.cls.next = {CODE['NMURRI']}u64.into();")
    a("            }")
    a("")
    a("        // ---- branch 2: ன்-final. The ன் -> ர் plural is suffix substitution, so it")
    a("        //      applies only where ன் IS the -அன் suffix; a monosyllable's ன் is root.")
    a(f"        }} else if (self.p1.val() == {N_:#04x}u64) & (self.len.val() > 1u64) {{")
    a("            self.ok.next = true;")
    a(f"            if (self.p2.val() == {A_:#04x}u64) & (self.uyir.val() == 1u64) {{")
    a(f"                self.cls.next = {CODE[CM['n/a/1']]}u64.into();   // n/a/1")
    a("            } else {")
    a(f"                self.cls.next = {CODE[CM['n/a/n']]}u64.into();   // n/a/n, n/x/1, n/x/n")
    a("            }")
    a("")
    a("        // ---- branch 3: உ-final, 3+ phonemes -> u/<p2>/<V|C>")
    a(f"        }} else if (self.p1.val() == {U:#04x}u64) & (self.len.val() > 2u64) {{")
    # u/XX/V and u/XX/C
    uv = {k: v for k, v in CM.items() if k.startswith("u/") and k.endswith("/V")}
    uc = {k: v for k, v in CM.items() if k.startswith("u/") and k.endswith("/C")}
    a("            if (self.p3.val() & 0xc0u64) == 0x00u64 {           // is_uyir(p3) -> V")
    _emit_p2_table(a, uv, 16)
    a("            } else {                                            // C")
    _emit_p2_table(a, uc, 16)
    a("            }")
    a("")
    a("        // ---- branch 4: உ-final, exactly 2 phonemes -> u/<p2>")
    a(f"        }} else if (self.p1.val() == {U:#04x}u64) & (self.len.val() > 1u64) {{")
    u2 = {k: v for k, v in CM.items() if k.startswith("u/") and k.count("/") == 1}
    if u2:
        _emit_p2_table(a, u2, 12)
    else:
        a("            // the fitted classifier has no bare u/<p2> context: 2-phoneme")
        a("            // உ-final stems never occur in the gold, so ok stays low")
    a("")
    a("        // ---- branch 5: everything else keys on the final phoneme alone")
    a("        } else {")
    _emit_p1_table(a, {k: v for k, v in CM.items() if "/" not in k}, 12)
    a("        }")
    a("    }")
    a("}")
    return "\n".join(L) + "\n"

def _emit_p2_table(a, ctx, ind):
    """if/else chain on p2 for the u/... contexts."""
    sp = " " * ind
    items = sorted(ctx.items(), key=lambda kv: kv[0])
    first = True
    for k, cls in items:
        byte = int(k.split("/")[1], 16)
        kw = "if" if first else "} else if"
        a(f"{sp}{kw} self.p2.val() == {byte:#04x}u64 {{   // {k} -> {cls}")
        a(f"{sp}    self.cls.next = {CODE[cls]}u64.into();")
        a(f"{sp}    self.ok.next = true;")
        first = False
    if items:
        a(f"{sp}}}")

def _emit_p1_table(a, ctx, ind):
    sp = " " * ind
    items = sorted(ctx.items(), key=lambda kv: int(kv[0], 16))
    first = True
    for k, cls in items:
        byte = int(k, 16)
        kw = "if" if first else "} else if"
        a(f"{sp}{kw} self.p1.val() == {byte:#04x}u64 {{   // {T.name(byte)} -> {cls}")
        a(f"{sp}    self.cls.next = {CODE[cls]}u64.into();")
        a(f"{sp}    self.ok.next = true;")
        first = False
    if items:
        a(f"{sp}}}")

# --------------------------------------------------------------------- oracle vectors
def window(b):
    """The five fields the hardware sees. Must match Tlp1Window exactly."""
    return (b[-1],
            b[-2] if len(b) > 1 else 0,
            b[-3] if len(b) > 2 else 0,
            min(len(b), 4),
            min(sum(1 for x in b if T.is_uyir(x)), 3))

def stems():
    seen = {}
    with open(ROOT / "data/derived/nouns_grid_final.tsv", encoding="utf-8") as f:
        for line in f:
            p = line.split("\t", 3)
            if len(p) >= 2: seen[p[0]] = p[1]
    return seen

def emit_vectors():
    d = D.Deriver()
    rows, skipped, byclass = [], 0, collections.Counter()
    for s in sorted(stems()):
        try: b = T.encode(s)
        except T.TLP1Error: skipped += 1; continue
        c = d.classify(s)
        w = window(b)
        code = CODE.get(c, 0) if c else 0
        rows.append((w, code, s, c))
        byclass[c] += 1
    # deduplicate on the window: the hardware cannot see anything else, and 43k stems
    # collapse to a few hundred distinct inputs
    uniq = {}
    for w, code, s, c in rows:
        if w in uniq and uniq[w][0] != code:
            raise SystemExit(f"window collision: {w} -> {uniq[w]} and {(code, s, c)}")
        uniq.setdefault(w, (code, s, c))
    hexs = []
    for w in sorted(uniq):
        code, s_, c = uniq[w]
        hexs.append(f"{w[0]:02x} {w[1]:02x} {w[2]:02x} {w[3]:x} {w[4]:x} "
                    f"{code:02x} {1 if code else 0:x}")
    out = ["# GENERATED by tools/gen_hdl.py from derive_nouns.classify() -- the oracle.",
           "# p1 p2 p3 len uyir  expect_cls expect_ok   # stem  class",
           f"# {len(rows):,} stems -> {len(uniq):,} distinct hardware windows"]
    for w in sorted(uniq):
        code, s, c = uniq[w]
        out.append(f"{w[0]:02x} {w[1]:02x} {w[2]:02x} {w[3]} {w[4]}  "
                   f"{code:02d} {1 if code else 0}   # {s} {c}")
    return ("\n".join(out) + "\n", "\n".join(hexs) + "\n",
            len(rows), len(uniq), skipped, byclass)

def emit_stem_vectors():
    """Whole-stem vectors: the byte stream, and the class the Python gives that stem.

    The window vectors test the decision. These test the window EXTRACTION too -- the
    shift register, the length saturation and the vowel counter -- by driving the actual
    TLP1 encoding of every stem in the gold, one phoneme per cycle.

    Format per line:  N cls ok b0 b1 ... b(N-1)     all hex
    """
    d = D.Deriver()
    rows = []
    for st in sorted(stems()):
        try: b = T.encode(st)
        except T.TLP1Error: continue
        c = d.classify(st)
        code = CODE.get(c, 0) if c else 0
        rows.append(f"{len(b):x} {code:02x} {1 if code else 0:x} "
                    + " ".join(f"{x:02x}" for x in b))
    return "\n".join(rows) + "\n", len(rows)

def emit_legend():
    L = ["// GENERATED by tools/gen_hdl.py -- class code legend.",
         "// 0 = context not present in the fitted classifier (ok low)."]
    for n, i in sorted(CODE.items(), key=lambda kv: kv[1]):
        L.append(f"`define CLS_{n:<7} {i:2d}")
    return "\n".join(L) + "\n"

def main():
    (HDL / "src").mkdir(parents=True, exist_ok=True)
    (HDL / "gen").mkdir(parents=True, exist_ok=True)
    (HDL / "vectors").mkdir(parents=True, exist_ok=True)
    (HDL / "src/classify_gen.rs").write_text(emit_rust(), encoding="utf-8")
    (HDL / "gen/tamil_classes.vh").write_text(emit_legend(), encoding="utf-8")
    svec, ns = emit_stem_vectors()
    (HDL / "vectors/stem_vectors.hex").write_text(svec, encoding="utf-8")
    vec, vhex, n, u, skipped, byclass = emit_vectors()
    (HDL / "vectors/class_vectors.txt").write_text(vec, encoding="utf-8")
    (HDL / "vectors/class_vectors.hex").write_text(vhex, encoding="utf-8")
    print(f"classes           : {len(CODE)}  {sorted(CODE, key=CODE.get)}")
    print(f"contexts          : {len(CM)}")
    print(f"stems             : {n:,}   unencodable skipped: {skipped}")
    print(f"distinct windows  : {u:,}")
    print(f"stem vectors      : {ns:,}")
    unc = byclass.get(None, 0)
    print(f"unclassified      : {unc:,}")
    if unc:
        sys.exit(f"\n{unc:,} stems have no class under {RULES_PATH.name}. The vectors would\n"
                 f"teach the hardware to answer 'no class' where the grammar has one.")
    print("wrote hdl/src/classify_gen.rs, hdl/gen/tamil_classes.vh,\n"
          "      hdl/vectors/class_vectors.txt (annotated), class_vectors.hex,\n"
          "      hdl/vectors/stem_vectors.hex (whole-stem streams)")

if __name__ == "__main__":
    main()
