#!/usr/bin/env python3
"""
The noun generator's tables and test vectors, from tools/noun_gen_model.py and tools/phon_rules.py.

  hdl/gen/tamil_noun_rom.vh        the class ROM and the morpheme ROM, as Verilog functions, read from
                                   phon_rules.STEMFORM and phon_rules.MORPH (never retyped)
  hdl/vectors/gen_vectors.hex      a stream of 32-bit words, one record per (stem, class, bundle) cell:
                                   stem_len, class, case_sel, flags, stem bytes, n_surfaces, then each
                                   surface as (len, bytes). The expected surfaces are phon_rules.derive().

    python3 tools/gen_noun_gen_hdl.py --sample 4000        # a stratified sample (committed size)
    python3 tools/gen_noun_gen_hdl.py --full --out PATH     # every cell (hundreds of MB; not committed)

Class code = the index in phon_rules.STEMFORM. case_sel: 0 none/nominative, 2..9 acc inst dat loc abl
gen soc so (the kind codes of hdl/rtl/tamil_noun_gen.sv).
"""
import sys, random, pathlib, collections
ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import tlp1 as T
import phon_rules as P
import noun_gen_model as M

KIND = {"pl": 0, "in": 1, "acc": 2, "inst": 3, "dat": 4, "loc": 5, "abl": 6, "gen": 7, "soc": 8, "so": 9,
        "ben": 10, "cmpr": 11, "foc": 12, "sandhik": 13, "sandhic": 14, "sandhip": 15, "sandhit": 16}
OUT_VH = ROOT / "hdl/gen/tamil_noun_rom.vh"
OUT_VEC = ROOT / "hdl/vectors/gen_vectors.hex"


def hexbytes(b, n):
    b = bytes(b) + b"\0" * (n - len(b))
    return "".join(f"{x:02x}" for x in reversed(b))          # byte 0 in the low bits


def rom_vh():
    L = ["// GENERATED by tools/gen_noun_gen_hdl.py from tools/phon_rules.py. Do not edit."]
    # class ROM: {plain_ok, uyar, dblfin, gem, inc_len[2:0], trunc, inc[31:0]}  (41 bits)
    L.append("function [40:0] class_rom(input [4:0] c);\n  case (c)")
    for i, name in enumerate(M.CLASSES):
        trunc, inc, gem, dblfin = P.STEMFORM[name]
        ib = P.B(inc) if inc else b""
        word = (int(name in P.PLAIN_OK) << 40) | (int(name in P.UYAR) << 39) | (int(dblfin) << 38) | (int(gem) << 37) \
            | (len(ib) << 34) | (trunc << 33) | int(hexbytes(ib, 4), 16)
        L.append(f"    5'd{i}: class_rom = 41'h{word:011x};   // {name}")
    L.append("    default: class_rom = 41'h0;\n  endcase\nendfunction\n")
    # morpheme ROM: {exists, starts_in, len[3:0], bytes[63:0]}  (70 bits)
    L.append("function [69:0] morph_rom(input [4:0] kind, input [1:0] ai);\n  case ({kind, ai})")
    for kname, k in KIND.items():
        alts = M.ALTS.get(kname, [])
        for ai, a in enumerate(alts):
            si = int(bool(a) and kname in M.CASE_ORDER and a[:len(M.IN_START)] == M.IN_START)
            word = (1 << 69) | (si << 68) | (len(a) << 64) | int(hexbytes(a, 8), 16)
            L.append(f"    {{5'd{k}, 2'd{ai}}}: morph_rom = 70'h{word:018x};   // {kname}[{ai}]")
    L.append("    default: morph_rom = 70'h0;\n  endcase\nendfunction")
    return "\n".join(L) + "\n"


def bundle_words(feat):
    bf = M.bundle(feat)
    case_sel = KIND[bf["case"]] if bf["case"] else 0
    sandhi = (M.SANDHI.index(bf["sandhi"]) + 1) if bf["sandhi"] else 0
    flags = (int(bf["pl"]) | (int(bf["ben"]) << 1) | (int(bf["cmpr"]) << 2) | (int(bf["foc"]) << 3)
             | (int(bf["obl"]) << 4) | (sandhi << 5))
    return case_sel, flags


def record(stem, cls_name, feat):
    want = P.derive(stem, cls_name, feat)
    if want is None: return None
    sb = P.B(stem)
    if len(sb) > 48: return None          # the generator's working buffer is 64 bytes; a stem of 48 plus an ending fits
    case_sel, flags = bundle_words(feat)
    w = [len(sb), M.CLASSES.index(cls_name), case_sel, flags] + list(sb)
    surfs = sorted(P.B(s) for s in want)
    w.append(len(surfs))
    for s in surfs: w += [len(s)] + list(s)
    return w


def main():
    OUT_VH.parent.mkdir(parents=True, exist_ok=True); OUT_VEC.parent.mkdir(parents=True, exist_ok=True)
    OUT_VH.write_text(rom_vh(), encoding="utf-8")
    out_vec = pathlib.Path(sys.argv[sys.argv.index("--out") + 1]) if "--out" in sys.argv else OUT_VEC
    full = "--full" in sys.argv
    n = int(sys.argv[sys.argv.index("--sample") + 1]) if "--sample" in sys.argv else 4000
    rows = list(P.rows())
    if not full:
        rng = random.Random(20261020)
        # stratify: every (class, bundle) pair is represented, then fill with random cells
        by = collections.defaultdict(list)
        for r in rows: by[(P.re.sub(r"(Sg|pl)Root$", "", r[1]), r[2])].append(r)
        pick = [rng.choice(v) for v in by.values()]
        pick += rng.sample(rows, max(0, n - len(pick)))
        rows = pick
    cnt = 0
    with out_vec.open("w", encoding="utf-8") as f:
        for stem, cl, feat, _ in rows:
            rec = record(stem, P.re.sub(r"(Sg|pl)Root$", "", cl), feat)
            if rec is None: continue
            f.write(" ".join(f"{x:x}" for x in rec) + "\n"); cnt += 1
    print(f"wrote {OUT_VH.relative_to(ROOT)} and {cnt:,} cell records -> {out_vec}")


if __name__ == "__main__":
    main()
